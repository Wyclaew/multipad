import Carbon
import Cocoa
import FlutterMacOS

@main
class AppDelegate: FlutterAppDelegate, NSWindowDelegate {
  private let channelName = "com.multipad.multipad/native"
  private var methodChannel: FlutterMethodChannel?
  private weak var attachedWindow: NSWindow?

  private var statusItem: NSStatusItem?
  private var trayEnabled: Bool = true
  private var globalHotkeyEnabled: Bool = true
  private var isExplicitQuit: Bool = false

  private var hotKeyRef: EventHotKeyRef?
  private var eventHandlerRef: EventHandlerRef?

  func attachMethodChannel(viewController: FlutterViewController, window: NSWindow) {
    self.attachedWindow = window
    let channel = FlutterMethodChannel(
      name: channelName,
      binaryMessenger: viewController.engine.binaryMessenger
    )
    self.methodChannel = channel

    channel.setMethodCallHandler { [weak self] call, result in
      guard let self = self else {
        result(false)
        return
      }
      switch call.method {
      case "copyConfidential":
        let args = call.arguments as? [String: Any]
        let text = args?["text"] as? String ?? ""
        self.copyToConfidentialPasteboard(text)
        result(true)

      case "configureDesktopShell":
        let args = call.arguments as? [String: Any]
        let tray = args?["trayEnabled"] as? Bool ?? true
        let hotkey = args?["globalHotkeyEnabled"] as? Bool ?? true
        DispatchQueue.main.async {
          self.trayEnabled = tray
          self.globalHotkeyEnabled = hotkey
          self.syncStatusItem()
          self.syncGlobalHotkey()
        }
        result(true)

      case "bringWindowToFront":
        DispatchQueue.main.async {
          self.showMainWindow()
        }
        result(true)

      case "setFlagSecure", "setMulticastLock":
        result(true)

      default:
        result(FlutterMethodNotImplemented)
      }
    }

    syncStatusItem()
    syncGlobalHotkey()
  }

  private func copyToConfidentialPasteboard(_ text: String) {
    let pasteboard = NSPasteboard.general
    pasteboard.clearContents()

    let item = NSPasteboardItem()
    item.setString(text, forType: .string)
    item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
    item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
    item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
    pasteboard.writeObjects([item])
  }

  private func syncStatusItem() {
    if !trayEnabled {
      if let existing = statusItem {
        NSStatusBar.system.removeStatusItem(existing)
        statusItem = nil
      }
      return
    }

    if statusItem == nil {
      let item = NSStatusBar.system.statusItem(withLength: NSStatusItem.squareLength)
      if let button = item.button {
        if let img = NSImage(systemSymbolName: "lock.shield", accessibilityDescription: "MultiPad") {
          img.isTemplate = true
          button.image = img
        } else {
          button.title = "MP"
        }
      }

      let menu = NSMenu()
      let showItem = NSMenuItem(
        title: "MultiPad'i Göster",
        action: #selector(handleShowWindow),
        keyEquivalent: ""
      )
      showItem.target = self
      menu.addItem(showItem)

      let quickItem = NSMenuItem(
        title: "Hızlı Arama (⌘⇧Space)",
        action: #selector(handleQuickSearch),
        keyEquivalent: ""
      )
      quickItem.target = self
      menu.addItem(quickItem)

      let lockItem = NSMenuItem(
        title: "Kasayı Kilitle",
        action: #selector(handleLockVault),
        keyEquivalent: "l"
      )
      lockItem.target = self
      menu.addItem(lockItem)

      menu.addItem(NSMenuItem.separator())

      let quitItem = NSMenuItem(
        title: "Çıkış",
        action: #selector(handleQuit),
        keyEquivalent: "q"
      )
      quitItem.target = self
      menu.addItem(quitItem)

      item.menu = menu
      statusItem = item
    }
  }

  private func syncGlobalHotkey() {
    if !globalHotkeyEnabled {
      unregisterGlobalHotkey()
      return
    }

    if hotKeyRef != nil {
      return
    }

    var eventSpec = EventTypeSpec(
      eventClass: OSType(kEventClassKeyboard),
      eventKind: UInt32(kEventHotKeyPressed)
    )

    let selfPtr = Unmanaged.passUnretained(self).toOpaque()
    InstallEventHandler(
      GetApplicationEventTarget(),
      { _, eventRef, userData -> OSStatus in
        guard let userData = userData, let eventRef = eventRef else {
          return OSStatus(eventNotHandledErr)
        }
        var hkID = EventHotKeyID()
        let status = GetEventParameter(
          eventRef,
          EventParamName(kEventParamDirectObject),
          EventParamType(typeEventHotKeyID),
          nil,
          MemoryLayout<EventHotKeyID>.size,
          nil,
          &hkID
        )
        if status == noErr && hkID.id == 1 {
          let delegate = Unmanaged<AppDelegate>.fromOpaque(userData).takeUnretainedValue()
          DispatchQueue.main.async {
            delegate.triggerQuickSearchFromHotkey()
          }
          return noErr
        }
        return OSStatus(eventNotHandledErr)
      },
      1,
      &eventSpec,
      selfPtr,
      &eventHandlerRef
    )

    var hotKeyID = EventHotKeyID()
    hotKeyID.signature = OSType(0x4D50484B) // 'MPHK'
    hotKeyID.id = 1

    RegisterEventHotKey(
      UInt32(kVK_Space),
      UInt32(cmdKey | shiftKey),
      hotKeyID,
      GetApplicationEventTarget(),
      0,
      &hotKeyRef
    )
  }

  private func unregisterGlobalHotkey() {
    if let ref = hotKeyRef {
      UnregisterEventHotKey(ref)
      hotKeyRef = nil
    }
    if let handler = eventHandlerRef {
      RemoveEventHandler(handler)
      eventHandlerRef = nil
    }
  }

  private func showMainWindow() {
    let win = attachedWindow ?? mainFlutterWindow
    win?.makeKeyAndOrderFront(nil)
    NSApp.activate(ignoringOtherApps: true)
  }

  private func triggerQuickSearchFromHotkey() {
    showMainWindow()
    methodChannel?.invokeMethod("onQuickSearchRequested", arguments: nil)
  }

  @objc private func handleShowWindow() {
    showMainWindow()
  }

  @objc private func handleQuickSearch() {
    triggerQuickSearchFromHotkey()
  }

  @objc private func handleLockVault() {
    methodChannel?.invokeMethod("onLockVaultRequested", arguments: nil)
  }

  @objc private func handleQuit() {
    isExplicitQuit = true
    NSApp.terminate(nil)
  }

  func windowShouldClose(_ sender: NSWindow) -> Bool {
    if trayEnabled && !isExplicitQuit {
      sender.orderOut(nil)
      return false
    }
    return true
  }

  override func applicationShouldHandleReopen(
    _ sender: NSApplication,
    hasVisibleWindows flag: Bool
  ) -> Bool {
    if !flag {
      showMainWindow()
    }
    return true
  }

  override func applicationShouldTerminate(_ sender: NSApplication) -> NSApplication.TerminateReply {
    isExplicitQuit = true
    return .terminateNow
  }

  override func applicationShouldTerminateAfterLastWindowClosed(_ sender: NSApplication) -> Bool {
    return !trayEnabled
  }

  override func applicationSupportsSecureRestorableState(_ app: NSApplication) -> Bool {
    return true
  }

  override func applicationWillTerminate(_ notification: Notification) {
    unregisterGlobalHotkey()
    if let existing = statusItem {
      NSStatusBar.system.removeStatusItem(existing)
      statusItem = nil
    }
    super.applicationWillTerminate(notification)
  }
}
